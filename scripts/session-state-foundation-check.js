const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { fixture, createCvaDraft } = require('./helpers/session-state-fixture');
async function main() {
  const env = fixture(path.join(fs.mkdtempSync(path.join(os.tmpdir(), 'cup-foundation-')), 'state.db'));
  const sampleId = await env.create('cva');
  const repo = () => env.repo;
  await env.save('cva', sampleId, createCvaDraft(1));
  assert.equal((await repo().getLocalTastingPresentation('cva')).tasting.started, false, 'default-only explicit Save does not start');
  const note = { ...createCvaDraft(1), general_affective_notes: 'Floral' };
  await env.save('cva', sampleId, note);
  assert.equal((await repo().getLocalTastingPresentation('cva')).session.status, 'in_progress', 'first saved note starts');
  assert.equal((await repo().getLocalTastingPresentation('cva', { purpose:'setup' })).identityHidden, true);
  await env.save('cva', sampleId);
  assert.equal((await env.complete('cva')).status, 'complete');
  let state = await repo().getLocalTastingPresentation('cva');
  assert.equal(state.session.status, 'complete');
  assert.equal(state.identityHidden, false);
  const first = env.sqlite.prepare('SELECT * FROM local_tasting_completions').all();
  const firstEvent = env.sqlite.prepare('SELECT * FROM local_tasting_completion_events').all();
  const revision = state.tasting.savedRevision;
  await env.save('cva', sampleId);
  state = await repo().getLocalTastingPresentation('cva');
  assert.equal(state.tasting.savedRevision, revision, 'no-op retains semantic revision');
  assert.equal(state.tasting.completedAt, firstEvent[0].completed_at);
  const changed = env.response(); changed.affective_notes.flavor_aftertaste = 'Cocoa';
  const ack = await env.save('cva', sampleId, changed);
  assert.equal(ack.identity.visible, false, 'Save ack refreshes identity');
  assert.equal(ack.access.canWrite, true, 'current local completion remains editable');
  state = await repo().getLocalTastingPresentation('cva');
  assert.equal(state.tasting.savedRevision, revision + 1);
  assert.equal(state.tasting.everCompleted, true);
  assert.equal(state.session.status, 'in_progress');
  assert.equal(state.identityHidden, true);
  await assert.rejects(repo().completeLocalTasting('cva', {expectedContextToken: ack.tasting.contextToken + 'stale'}), /stale_context/);
  env.failAt('INSERT INTO local_tasting_completion_events');
  await assert.rejects(env.complete('cva'), /injected/); env.failAt(null);
  assert.equal((await repo().getLocalTastingPresentation('cva')).tasting.completed, false);
  await env.complete('cva');
  assert.deepEqual(env.sqlite.prepare('SELECT * FROM local_tasting_completions').all(), first, 'first completion evidence unchanged');
  assert.equal(env.sqlite.prepare('SELECT COUNT(*) AS n FROM local_tasting_completion_events').get().n, 2);
  env.restart();
  assert.equal((await repo().getLocalTastingPresentation('cva')).identityHidden, false);
  assert.equal((await repo().getCvaResponse('cva', sampleId)).result.display_score, '89.50');
  // An untracked changed roster must not be blessed by a fresh token.
  env.sqlite.prepare('UPDATE samples SET sample_number=8 WHERE id=?').run(sampleId);
  assert.equal((await repo().getLocalTastingPresentation('cva')).identityHidden, true);
  await assert.rejects(env.complete('cva'), /stale_content/);
  env.sqlite.prepare('UPDATE samples SET sample_number=7 WHERE id=?').run(sampleId);
  assert.equal((await repo().getLocalTastingPresentation('cva')).identityHidden, false);
  env.actor(env.actorB);
  assert.equal((await repo().getLocalTastingPresentation('cva')).identityHidden, true);
  await assert.rejects(env.save('cva', sampleId), /foreign_stream/);
  env.actor(env.actorA);
  // Participant roster: actual new sample reopens, existing rescan does not.
  env.sqlite.prepare('UPDATE sessions SET local_creator_profile_id=NULL WHERE id=?').run('cva');
  const second = await repo().upsertSessionSampleFromCupMetadata({ sessionId:'cva',cupUUID:'OTHER',coffeeNameOrigin:'Second',process:'1',cupNumber:1,cuppingForm:1,cuppingMode:'blind',sampleNumber:12 });
  assert.equal((await repo().getLocalTastingPresentation('cva')).identityHidden, true);
  assert.equal((await env.complete('cva')).status, 'incomplete');
  await env.save('cva', second.id); await env.complete('cva');
  const beforeRescan = (await repo().getLocalTastingPresentation('cva')).tasting.savedRevision;
  await repo().upsertSessionSampleFromCupMetadata({ sessionId:'cva',cupUUID:'OTHER',coffeeNameOrigin:'Second',process:'1',cupNumber:1,cuppingForm:1,cuppingMode:'blind',sampleNumber:12 });
  assert.equal((await repo().getLocalTastingPresentation('cva')).tasting.savedRevision, beforeRescan);
  assert.equal((await repo().getLocalTastingPresentation('cva')).tasting.completed, true);
  const legacyId = await env.create('legacy', 2);
  const legacy = env.legacy();
  await repo().saveLegacyResponse({sessionId:'legacy',sampleId:legacyId,response:legacy,complete:true});
  await env.complete('legacy');
  const legacyBefore = env.sqlite.prepare('SELECT * FROM legacy_responses WHERE sample_id=?').get(legacyId);
  const legacyState = await repo().getLegacyResponse('legacy',legacyId);
  assert.equal(legacyState.sessionComplete, false);
  const draft = {...legacy,notes:'unsaved recovery note'};
  await repo().saveLegacyResponse({sessionId:'legacy',sampleId:legacyId,response:draft,intent:'recovery',expectedFingerprint:legacyState.savedFingerprint});
  assert.deepEqual(env.sqlite.prepare('SELECT * FROM legacy_responses WHERE sample_id=?').get(legacyId),legacyBefore);
  assert.equal((await repo().getLocalTastingPresentation('legacy')).tasting.completed,true);
  env.restart();
  const recovered = await repo().getLegacyResponse('legacy',legacyId);
  assert.equal(recovered.recoveryDraft.notes,draft.notes);
  await repo().discardLegacyRecoveryDraft({sessionId:'legacy',sampleId:legacyId,expectedFingerprint:recovered.savedFingerprint});
  assert.equal((await repo().getLegacyResponse('legacy',legacyId)).recoveryDraft,null);
  await repo().saveLegacyResponse({sessionId:'legacy',sampleId:legacyId,response:draft,complete:true,expectedFingerprint:recovered.savedFingerprint});
  assert.equal((await repo().getLocalTastingPresentation('legacy')).tasting.completed,false);
  await assert.rejects(repo().saveLegacyResponse({sessionId:'legacy',sampleId:legacyId,response:legacy,complete:true,expectedFingerprint:recovered.savedFingerprint}),/stale_context/);
  await env.complete('legacy');
  assert.equal((await repo().getLocalTastingPresentation('legacy')).tasting.everCompleted,true);
  const empty = await env.create('empty',1,'blind',false);
  assert.ok(empty);
  assert.equal((await repo().getLocalTastingPresentation('empty')).session.status,'new');
  await assert.rejects(env.complete('empty'),/unavailable/);
  env.sqlite.prepare('INSERT INTO local_session_foundations VALUES (?,1,0,0)').run('empty');
  env.sqlite.prepare("UPDATE sessions SET status='damaged' WHERE id=?").run('empty');
  assert.equal((await repo().getSessionSetupAccess('empty')).canManageSetup,false,'unknown state cannot restore setup authority');
  await assert.rejects(repo().getLocalTastingPresentation('empty',{purpose:'setup'}),/damaged_history/);
  await assert.rejects(repo().recomputeSessionProgressStatus('empty'),/damaged_history/);
  assert.equal((await repo().getSessionById('empty')).status,'damaged');
  assert.equal((await repo().listSessions()).find(row=>row.id==='empty').status,'damaged');
  const unknown = fixture(); const unknownId = await unknown.create('unknown-state');
  const unknownRead = await unknown.repo.getCvaResponse('unknown-state',unknownId);
  unknown.sqlite.prepare('INSERT INTO local_session_foundations VALUES (?,1,0,0)').run('unknown-state');
  unknown.sqlite.prepare("UPDATE sessions SET status='damaged' WHERE id=?").run('unknown-state');
  await assert.rejects(unknown.repo.saveCvaResponse({sessionId:'unknown-state',sampleId:unknownId,response:{...createCvaDraft(1),general_affective_notes:'Do not save'},
    expectedRevision:unknownRead.revision,expectedIdentity:unknownRead.trusted.identity,expectedCupCount:unknownRead.n}),/unsupported_session_state/);
  await assert.rejects(unknown.repo.saveSessionWithSamples({existingSessionId:'unknown-state',sessionUUID:'unknown-state',sessionName:'Do not repair',cuppingForm:1,samples:[]}),/damaged_history|setup_started/);
  assert.equal(unknown.sqlite.prepare('SELECT COUNT(*) n FROM cva_response_revisions').get().n,0);
  assert.equal(unknown.sqlite.prepare('SELECT status FROM sessions').get().status,'damaged');
  const invalidSetup = fixture(); await invalidSetup.create('invalid-setup');
  const originalHash=invalidSetup.sqlite.prepare('SELECT form_hash FROM sessions').get().form_hash;
  invalidSetup.sqlite.prepare('UPDATE sessions SET form_hash=?').run('unknown-form');
  assert.equal((await invalidSetup.repo.getSessionSetupAccess('invalid-setup')).canManageSetup,false);
  await assert.rejects(invalidSetup.repo.getOwnedSessionSetup('invalid-setup'),/Only the local profile/);
  invalidSetup.sqlite.prepare("UPDATE sessions SET form_hash=?,cupping_mode='blind'").run(originalHash);
  invalidSetup.sqlite.prepare('UPDATE samples SET cupping_form=2').run();
  assert.equal((await invalidSetup.repo.getSessionSetupAccess('invalid-setup')).canManageSetup,false);
  await assert.rejects(invalidSetup.repo.getOwnedSessionSetup('invalid-setup'),/Only the local profile/);
  invalidSetup.sqlite.prepare('UPDATE samples SET cupping_form=1').run();
  invalidSetup.sqlite.prepare('UPDATE sessions SET form_hash=?,cupping_mode=?').run(originalHash,'invalid-mode');
  assert.equal((await invalidSetup.repo.getSessionSetupAccess('invalid-setup')).canManageSetup,false);
  await assert.rejects(invalidSetup.repo.getOwnedSessionSetup('invalid-setup'),/Only the local profile/);
  const noMode = fixture();
  await noMode.repo.saveSessionWithSamples({sessionUUID:'no-mode',sessionName:'Empty creator draft',sessionType:'Training Session',sessionDate:'18 Oct 2026',cuppingForm:1,samples:[]});
  assert.equal((await noMode.repo.getSessionSetupAccess('no-mode')).canManageSetup,true);
  assert.equal((await noMode.repo.getOwnedSessionSetup('no-mode')).samples.length,0);
  // An explicitly contradictory history latch cannot restore preparation.
  env.sqlite.prepare('UPDATE local_session_foundations SET ever_started=0,ever_completed=0 WHERE session_id=?').run('cva');
  await assert.rejects(repo().getLocalTastingPresentation('cva',{purpose:'setup'}),/damaged_history/);
  const historical = fixture(); const historicalId = await historical.create('historical');
  await historical.save('historical',historicalId);
  historical.sqlite.prepare("UPDATE sessions SET status='complete' WHERE id=?").run('historical');
  historical.sqlite.prepare('DELETE FROM local_session_foundations WHERE session_id=?').run('historical');
  const historicalState = await historical.repo.getLocalTastingPresentation('historical');
  assert.equal(historicalState.session.status,'complete');
  assert.equal(historicalState.identityHidden,true);
  assert.equal(historicalState.tasting.canComplete,false);
  assert.equal((await historical.repo.getCvaResponse('historical',historicalId)).sessionComplete,true);
  await assert.rejects(historical.complete('historical'),/unavailable/);
  assert.equal(historical.sqlite.prepare('SELECT COUNT(*) AS n FROM local_tasting_completion_events').get().n,0);
  // Explicit adoption cannot bless corruption of another sample's tracked context.
  const adoption = fixture(); const owned = await adoption.create('adoption');
  const sourceId = await adoption.create('source'); await adoption.save('source',sourceId);
  const source = adoption.sqlite.prepare('SELECT * FROM cva_response_revisions WHERE session_id=?').get('source');
  const now = new Date().toISOString();
  adoption.sqlite.prepare(`INSERT INTO samples(id,session_id,cup_uuid,cup_number,cupping_form,cupping_mode,sample_number,
    coffee_name_origin,process,position_index,created_at,updated_at) VALUES ('old-sample','adoption','OLD-TAG',1,1,'blind',10,'Old coffee','1',1,?,?)`).run(now,now);
  const columns = Object.keys(source);
  adoption.sqlite.prepare(`INSERT INTO cva_response_revisions(${columns.join(',')}) VALUES (${columns.map(()=>'?').join(',')})`)
    .run(...columns.map(key=>key==='id'?'old-source':key==='session_id'?'adoption':key==='sample_id'?'old-sample':source[key]));
  await adoption.save('adoption',owned);
  adoption.sqlite.prepare('UPDATE samples SET sample_number=77 WHERE id=?').run(owned);
  const old = await adoption.repo.getCvaResponse('adoption','old-sample');
  const beforeAdopt = adoption.sqlite.prepare('SELECT * FROM local_tasting_revisions WHERE session_id=?').all('adoption');
  await assert.rejects(adoption.repo.adoptSavedTasting({sessionId:'adoption',sampleId:'old-sample',expectedSourceToken:old.access.sourceToken}),/stale_content/);
  assert.deepEqual(adoption.sqlite.prepare('SELECT * FROM local_tasting_revisions WHERE session_id=?').all('adoption'),beforeAdopt);
  adoption.sqlite.prepare('UPDATE samples SET sample_number=7 WHERE id=?').run(owned);
  const adoptionRead = await adoption.repo.getCvaResponse('adoption','old-sample');
  adoption.afterCommit(()=>adoption.actor(adoption.actorB));
  await assert.rejects(adoption.repo.adoptSavedTasting({sessionId:'adoption',sampleId:'old-sample',expectedSourceToken:adoptionRead.access.sourceToken}),/actor_changed/);
  assert.equal(adoption.sqlite.prepare('SELECT local_profile_id FROM local_response_streams WHERE sample_id=?').get('old-sample').local_profile_id,adoption.actorA,'durable adoption remains committed when acknowledgement is rejected');
  const recovery = fixture(); const recoveryId = await recovery.create('recovery',2);
  await recovery.repo.saveLegacyResponse({sessionId:'recovery',sampleId:recoveryId,response:recovery.legacy(),complete:true});
  await recovery.repo.saveLegacyResponse({sessionId:'recovery',sampleId:recoveryId,response:{...recovery.legacy(),notes:'draft'},intent:'recovery'});
  const savedDraft = recovery.sqlite.prepare('SELECT * FROM local_legacy_recovery_drafts').get();
  recovery.sqlite.prepare('UPDATE local_legacy_recovery_drafts SET context_json=?').run('{}');
  await assert.rejects(recovery.repo.getLegacyResponse('recovery',recoveryId),/damaged_draft/);
  recovery.sqlite.prepare('UPDATE local_legacy_recovery_drafts SET context_json=?,updated_at=?').run(savedDraft.context_json,'invalid');
  await assert.rejects(recovery.repo.getLegacyResponse('recovery',recoveryId),/damaged_draft/);
  recovery.sqlite.prepare('UPDATE local_legacy_recovery_drafts SET updated_at=?').run(savedDraft.updated_at);
  const originalGet = recovery.storage.get.bind(recovery.storage); let reads=0;
  recovery.storage.get = key => {
    if (key==='cup_app:user_profile' && ++reads===3) recovery.actor(recovery.actorB);
    return originalGet(key);
  };
  await assert.rejects(recovery.repo.getLegacyResponse('recovery',recoveryId),/actor_changed/);
  // A successful durable Save must not acknowledge a different actor or a later
  // competing response. Rejecting readback leaves the committed rows intact.
  const ackActor = fixture(); const ackId = await ackActor.create('ack-actor');
  const initial = await ackActor.repo.getCvaResponse('ack-actor',ackId);
  ackActor.afterCommit(()=>ackActor.actor(ackActor.actorB));
  await assert.rejects(ackActor.repo.saveCvaResponse({sessionId:'ack-actor',sampleId:ackId,response:ackActor.response(),
    expectedRevision:initial.revision,expectedIdentity:initial.trusted.identity,expectedCupCount:initial.n}),/actor_changed/);
  assert.equal(ackActor.sqlite.prepare('SELECT COUNT(*) n FROM cva_response_revisions').get().n,1);
  ackActor.actor(ackActor.actorA);
  assert.equal((await ackActor.repo.getCvaResponse('ack-actor',ackId)).revision,1);
  const ackRace = fixture(); const raceId = await ackRace.create('ack-race');
  const raceInitial = await ackRace.repo.getCvaResponse('ack-race',raceId);
  ackRace.afterCommit(()=>{
    const row = ackRace.sqlite.prepare('SELECT * FROM cva_response_revisions').get(), keys=Object.keys(row);
    ackRace.sqlite.prepare(`INSERT INTO cva_response_revisions(${keys.join(',')}) VALUES (${keys.map(()=>'?').join(',')})`)
      .run(...keys.map(key=>key==='id'?'competing-noop':key==='revision'?2:row[key]));
  });
  await assert.rejects(ackRace.repo.saveCvaResponse({sessionId:'ack-race',sampleId:raceId,response:ackRace.response(),
    expectedRevision:raceInitial.revision,expectedIdentity:raceInitial.trusted.identity,expectedCupCount:raceInitial.n}),/ack_changed/);
  assert.equal(ackRace.sqlite.prepare('SELECT COUNT(*) n FROM cva_response_revisions').get().n,2);
  const legacyRace = fixture(); const legacyRaceId = await legacyRace.create('legacy-race',2);
  legacyRace.afterCommit(()=>{
    const row=legacyRace.sqlite.prepare('SELECT response_json FROM legacy_responses').get();
    legacyRace.sqlite.prepare('UPDATE legacy_responses SET response_json=?').run(JSON.stringify({...JSON.parse(row.response_json),notes:'later competing revision'}));
  });
  await assert.rejects(legacyRace.repo.saveLegacyResponse({sessionId:'legacy-race',sampleId:legacyRaceId,response:legacyRace.legacy(),complete:true}),/ack_changed/);
  assert.equal(JSON.parse(legacyRace.sqlite.prepare('SELECT response_json FROM legacy_responses').get().response_json).notes,'later competing revision');
  console.log('State foundation: semantic Save/no-op/recompletion, history, privacy, actor/stale guards, scanned coverage, Legacy recovery and empty completion PASS.');
}
main().catch(error=>{console.error(error);process.exitCode=1;});
